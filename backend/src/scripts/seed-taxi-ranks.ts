export async function seedTaxiRanks(pool: any) {
  console.log(`Seeding ${taxiRanksSeed.length} taxi ranks...`);

  for (const rank of taxiRanksSeed) {
    await pool.query(
      `
      INSERT INTO public.taxi_ranks (
        name,
        location,
        source,
        verified
      )
      VALUES (
        $1,
        ST_SetSRID(ST_MakePoint($2, $3), 4326),
        $4,
        false
      )
      `,
      [rank.name, rank.lng, rank.lat, 'Seeded'],
    );
  }

  console.log(`✓ Seeded ${taxiRanksSeed.length} taxi ranks`);
}

async function main() {
  try {
    await seedTaxiRanks(pool);
  } catch (error) {
    console.error('❌ Failed to seed taxi ranks:', error);
    process.exitCode = 1;
  } finally {
    await pool.end();
  }
}

